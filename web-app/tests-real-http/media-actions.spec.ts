import { expect, test } from '@playwright/test'

test('rate and save from the poster menu, then restore both from a fresh page', async ({ page }) => {
  await page.goto('/')
  await page.getByTestId('profile-card').filter({ hasText: 'Fixture Clean' }).click()
  await expect(page.getByTestId('home')).toBeVisible()
  await page.goto('/search?q=Star%20Wars')
  const openMenu = () => page.getByRole('button', { name: 'More actions for Star Wars: The Force Awakens', exact: true }).click()
  await openMenu()
  await expect(page.getByRole('menuitem', { name: 'Remove from library' })).toHaveCount(0)
  await page.getByRole('menuitem', { name: 'Thumbs up', exact: true }).click()
  await expect(page.getByRole('menuitem', { name: 'Remove thumbs up' })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('menuitem', { name: 'Add to My List' }).click()
  await expect(page.getByRole('menuitem', { name: 'Remove from My List' })).toBeVisible()
  await page.reload()
  await openMenu()
  await page.getByRole('menuitem', { name: 'Remove thumbs up' }).click()
  await expect(page.getByRole('menuitem', { name: 'Thumbs up', exact: true })).toHaveAttribute('aria-pressed', 'false')
  await page.getByRole('menuitem', { name: 'Remove from My List' }).click()
  await expect(page.getByRole('menuitem', { name: 'Add to My List' })).toBeVisible()
})

test('the owner can cancel or undo removing a poster from the household library', async ({ page }) => {
  await page.goto('/')
  await page.getByTestId('profile-card').filter({ hasText: 'Admin' }).first().click()
  await page.getByLabel('Password', { exact: true }).fill('fixture-only-admin-password')
  await page.keyboard.press('Enter')
  const accept = page.getByRole('button', { name: 'I accept', exact: true })
  await expect(accept.or(page.getByTestId('home')).first()).toBeVisible()
  if (await accept.isVisible()) await accept.click()
  await expect(page.getByTestId('home')).toBeVisible()
  await page.goto('/search?q=Star%20Wars')
  const title = page.getByRole('link', { name: 'Star Wars: The Force Awakens', exact: true })
  const menu = page.getByRole('button', { name: 'More actions for Star Wars: The Force Awakens', exact: true })
  const confirm = page.getByTestId('remove-library-confirm')
  await menu.click()
  await page.getByRole('menuitem', { name: 'Remove from library' }).click()
  await expect(confirm.getByRole('button', { name: 'Cancel' })).toBeFocused()
  await confirm.getByRole('button', { name: 'Cancel' }).click()
  await expect(title).toBeVisible()
  await menu.click()
  await page.getByRole('menuitem', { name: 'Remove from library' }).click()
  await confirm.getByRole('button', { name: 'Remove', exact: true }).click()
  await expect(title).toHaveCount(0)
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(title).toBeVisible()
})
