import { expect, test } from '@playwright/test'

const PIN = '629417' // Synthetic disposable fixture only; never a real credential.

test('real pending Google identity, local PIN enrollment, policy grant, restricted exit and retained SSO', async ({ page, context }) => {
  await context.route('**/*', async (route) => {
    const url = new URL(route.request().url())
    if (url.origin === 'http://127.0.0.1:5188' || ['data:', 'blob:'].includes(url.protocol)) await route.continue()
    else await route.abort('blockedbyclient')
  })
  const pendingResponse = page.waitForResponse((r) => r.url().endsWith('/auth/google/complete'))
  const statusResponse = page.waitForResponse((r) => r.url().endsWith('/auth/owner-pin/setup-status'))
  await page.goto('/__fixture/google-login')
  const pending = await (await pendingResponse).json()
  expect(pending.owner_pin_required).toBe(true)
  expect(pending.access_token).toBeUndefined()
  expect(await page.evaluate(() => localStorage.getItem('sh.session.v1'))).toBeNull()
  const status = await (await statusResponse).json()
  await expect(page.getByText('Waiting for local VM approval.', { exact: false })).toBeVisible()
  expect((await page.request.post('/__fixture/local-approve-setup', { data: { request_id: status.setup_request_id } })).status()).toBe(200)
  await page.getByRole('button', { name: 'Check local approval', exact: true }).click()
  await page.getByLabel('New owner PIN', { exact: true }).fill(PIN)
  await page.getByLabel('Confirm new owner PIN', { exact: true }).fill(PIN)
  await page.getByRole('button', { name: 'Set owner PIN', exact: true }).click()
  await page.getByTestId('disclaimer-accept').click()
  await expect(page.getByTestId('home')).toBeVisible()
  const owner = await page.evaluate(() => JSON.parse(localStorage.getItem('sh.session.v1') ?? '{}'))

  await page.goto('/settings?tab=parental')
  await page.getByTestId('content-policies').getByRole('button', { name: 'Fixture Child', exact: true }).click()
  const editor = page.getByTestId('policy-editor')
  await editor.getByRole('button', { name: 'Restrictions off', exact: true }).click()
  await editor.getByRole('button', { name: 'PG', exact: true }).click()
  await editor.getByRole('button', { name: 'Save restrictions for Fixture Child', exact: true }).click()
  const saved = page.waitForResponse((r) => r.url().endsWith('/profiles/fixture-child/content-policy') && r.request().method() === 'PUT')
  await page.getByLabel('Owner PIN', { exact: true }).fill(PIN)
  await page.getByRole('button', { name: 'Authorize with owner PIN', exact: true }).click()
  expect((await saved).status()).toBe(200)

  await page.goto('/settings?tab=profiles')
  await page.getByTestId('switch-profile').click()
  await page.getByRole('dialog').getByRole('button', { name: 'Fixture Child', exact: true }).click()
  await page.getByRole('button', { name: 'Continue as Fixture Child', exact: true }).click()
  await expect(page.getByTestId('home')).toBeVisible()
  const childSession = await page.evaluate(() => JSON.parse(localStorage.getItem('sh.session.v1') ?? '{}'))
  expect(childSession.profile.content_restricted).toBe(true)
  const child = { Authorization: `Bearer ${childSession.access}` }
  await page.goto('/search')
  await page.getByLabel('Search titles and channels').fill('Star Wars')
  const results = page.getByTestId('group-relevance').getByRole('link')
  await expect(results).toHaveCount(1)
  await expect(results.first()).toHaveAccessibleName('Star Wars')
  const denied = await page.request.post('/api/v1/playback/resolve', { headers: child, data: {
    id: 'lib:fixture-iptv:en', variant_id: 'lib:fixture-iptv:en', allow_unverified_audio: true, client: 'android_tv',
  } })
  expect(denied.status()).toBe(403)
  expect((await denied.json()).code).toBe('content_restricted')

  await page.goto('/settings?tab=profiles')
  await page.getByTestId('switch-profile').click()
  await page.getByRole('dialog').getByRole('button', { name: owner.profile.name, exact: true }).click()
  await page.getByLabel('Owner PIN', { exact: true }).fill('000001')
  await page.getByRole('button', { name: 'Authorize with owner PIN', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Invalid owner PIN')
  await expect(page.getByLabel('Owner PIN', { exact: true })).toHaveValue('')
  const cancelled = page.waitForResponse((r) => r.url().endsWith('/auth/owner-pin/cancel'))
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel', exact: true }).click()
  expect((await cancelled).status()).toBe(204)
  await page.getByTestId('switch-profile').click()
  await page.getByRole('dialog').getByRole('button', { name: owner.profile.name, exact: true }).click()
  await page.getByLabel('Owner PIN', { exact: true }).fill(PIN)
  await page.getByRole('button', { name: 'Authorize with owner PIN', exact: true }).click()
  await expect(page.getByTestId('home')).toBeVisible()
  expect((await page.request.get('/api/v1/home', { headers: child })).status()).toBe(401)

  await page.evaluate(() => localStorage.clear())
  const repeatedLogin = page.waitForResponse((r) => r.url().endsWith('/auth/google/complete'))
  await page.goto('/__fixture/google-login')
  const repeated = await (await repeatedLogin).json()
  expect(repeated.owner_pin_required).toBe(true)
  expect(repeated.setup_required).toBe(false)
  expect(repeated.access_token).toBeUndefined()
  await expect(page.getByLabel('Owner PIN', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => localStorage.getItem('sh.session.v1'))).toBeNull()
  const pendingHeaders = { Authorization: `Bearer ${repeated.pending_token}` }
  expect((await page.request.get('/api/v1/home', { headers: pendingHeaders })).status()).toBe(401)
  expect([404, 405]).toContain((await page.request.post('/api/v1/auth/owner-pin/reset', { headers: pendingHeaders })).status())
  for (let i = 0; i < 4; i++) {
    await page.getByLabel('Owner PIN', { exact: true }).fill('000001')
    const attempt = page.waitForResponse((r) => r.url().endsWith('/auth/owner-pin/verify'))
    await page.getByRole('button', { name: 'Authorize with owner PIN', exact: true }).click()
    expect((await attempt).status()).toBe(403)
  }
  await page.getByLabel('Owner PIN', { exact: true }).fill(PIN)
  const limited = page.waitForResponse((r) => r.url().endsWith('/auth/owner-pin/verify'))
  await page.getByRole('button', { name: 'Authorize with owner PIN', exact: true }).click()
  expect((await limited).status()).toBe(429)
  await expect(page.getByRole('button', { name: 'Authorize with owner PIN', exact: true })).toBeDisabled()
  await expect(page.getByLabel('Owner PIN', { exact: true })).toHaveValue('')
})
