// Generates src/styles/tokens.css (Tailwind v4 @theme + per-theme CSS variables)
// and src/tokens.ts from ../design/tokens.json. Run: npm run gen:tokens
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')
const tokens = JSON.parse(readFileSync(resolve(root, '../design/tokens.json'), 'utf8'))

// 1 dp = 1/16 rem. <html> font-size scales with viewport (see base.css), so dp is responsive TV -> phone.
const rem = (dp) => `${+(dp / 16).toFixed(4)}rem`
const kebab = (s) => s.replace(/_/g, '-')

const themeKeys = ['bg', 'surface', 'surface_alt', 'overlay', 'text', 'text_muted', 'accent', 'accent_text',
  'focus_ring', 'focus_glow', 'danger', 'success', 'scrim_top', 'scrim_bottom']

const resolved = {}
for (const [id, t] of Object.entries(tokens.themes)) {
  const base = t.extends ? resolved[t.extends] : {}
  const merged = { ...base, ...t }
  for (const k of Object.keys(merged)) if (String(merged[k]).startsWith('dynamic:')) merged[k] = base[k]
  resolved[id] = merged
}

const out = []
out.push('/* GENERATED by scripts/gen-tokens.mjs from design/tokens.json. Do not edit. */')
out.push('@theme inline {')
out.push('  --color-*: initial;')
for (const k of themeKeys) out.push(`  --color-${kebab(k)}: var(--t-${kebab(k)});`)
out.push('  --color-transparent: transparent;')
out.push(`  --font-sans: ${tokens.type.family};`)
for (const [k, v] of Object.entries(tokens.radius)) out.push(`  --radius-${k}: ${k === 'pill' ? '999px' : rem(v)};`)
for (const [k, v] of Object.entries(tokens.spacing)) out.push(`  --spacing-${k}: ${rem(v)};`)
for (const k of ['display', 'title', 'heading', 'body', 'label']) {
  const t = tokens.type[k]
  out.push(`  --text-${k}: ${rem(t.size)};`)
  out.push(`  --text-${k}--line-height: ${t.line};`)
  out.push(`  --text-${k}--font-weight: ${t.weight};`)
}
out.push('}', '')

out.push(':root {')
out.push(`  --focus-scale: ${tokens.focus.scale};`)
out.push(`  --focus-border: ${rem(tokens.focus.border_dp)};`)
out.push(`  --focus-glow-blur: ${rem(tokens.focus.glow_blur_dp)};`)
out.push(`  --focus-glow-alpha: ${Math.round(tokens.focus.glow_alpha * 100)}%;`)
out.push(`  --dur-focus: ${tokens.focus.duration_ms}ms;`)
out.push(`  --ease: ${tokens.focus.easing};`)
for (const [k, v] of Object.entries(tokens.motion)) out.push(`  --dur-${kebab(k).replace(/-ms$/, '')}: ${v}ms;`)
for (const [k, v] of Object.entries(tokens.tile)) out.push(`  --tile-${kebab(k)}: ${rem(v)};`)
out.push(`  --rail-collapsed: ${rem(tokens.rail.collapsed_w)};`)
out.push(`  --rail-expanded: ${rem(tokens.rail.expanded_w)};`)
out.push(`  --safe-x: ${rem(tokens.canvas.safe_margin_dp.x)};`)
out.push(`  --safe-y: ${rem(tokens.canvas.safe_margin_dp.y)};`)
out.push('}', '')

for (const [id, t] of Object.entries(resolved)) {
  out.push(id === 'midnight' ? `:root, [data-theme='midnight'] {` : `[data-theme='${id}'] {`)
  out.push(`  color-scheme: ${id === 'light' ? 'light' : 'dark'};`)
  for (const k of themeKeys) out.push(`  --t-${kebab(k)}: ${t[k]};`)
  if (t.focus_scale_override) out.push(`  --focus-scale: ${t.focus_scale_override};`)
  if (t.focus_border_override) out.push(`  --focus-border: ${rem(t.focus_border_override)};`)
  out.push('}', '')
}
mkdirSync(resolve(root, 'src/styles'), { recursive: true })
writeFileSync(resolve(root, 'src/styles/tokens.css'), out.join('\n'))

const themeList = Object.entries(tokens.themes).map(([id, t]) => ({
  id, name: t.name ?? id, extendsId: t.extends ?? null, adaptive: Object.values(t).some((v) => String(v).startsWith('dynamic:')),
  colors: resolved[id],
}))
const ts = `// GENERATED by scripts/gen-tokens.mjs from design/tokens.json. Do not edit.
export const tokens = ${JSON.stringify(tokens, null, 2)} as const

export interface ThemeInfo {
  id: string
  name: string
  extendsId: string | null
  adaptive: boolean
  colors: Record<string, string | number>
}
export const themes: ThemeInfo[] = ${JSON.stringify(themeList, null, 2)}
export const defaultThemeId = 'midnight'
`
writeFileSync(resolve(root, 'src/tokens.ts'), ts)
console.log(`tokens: ${themeList.length} themes -> src/styles/tokens.css, src/tokens.ts`)
